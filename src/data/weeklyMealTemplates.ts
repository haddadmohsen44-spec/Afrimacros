/**
 * Returns dynamic weekly plan scaled to user's daily caloric target and program goal
 */
export function generatePersonalizedWeeklyPlan(
  targetAverageKcal: number = 1950,
  goal: ProgramGoal = 'fat_loss',
  regionalStyle: RegionalStyle = 'pan_algerian'
): WeeklyProgramPlan {
  const baseAvg = 2000;
  const scale = targetAverageKcal / baseAvg;

  const days: DailyProgram[] = BASE_WEEKLY_DAYS.map((day) => {
    // Friday gets a planned +15% carb / energy boost (cultural refuel)
    const dayScale = day.dayOfWeek === 'Friday' ? scale * 1.12 : scale * 0.98;

    const scaledMeals = day.meals.map((meal) => {
      const mealScale = dayScale;
      return {
        ...meal,
        portionGrams: Math.round(meal.portionGrams * mealScale),
        macros: {
          calories: Math.round(meal.macros.calories * mealScale),
          proteinGrams: Math.round(meal.macros.proteinGrams * mealScale * 10) / 10,
          carbsGrams: Math.round(meal.macros.carbsGrams * mealScale * 10) / 10,
          fatGrams: Math.round(meal.macros.fatGrams * mealScale * 10) / 10,
          fiberGrams: Math.round(meal.macros.fiberGrams * mealScale * 10) / 10,
        },
      };
    });

    const dayCalories = scaledMeals.reduce((acc, m) => acc + m.macros.calories, 0);
    const dayProtein = Math.round(scaledMeals.reduce((acc, m) => acc + m.macros.proteinGrams, 0));
    const dayCarbs = Math.round(scaledMeals.reduce((acc, m) => acc + m.macros.carbsGrams, 0));
    const dayFat = Math.round(scaledMeals.reduce((acc, m) => acc + m.macros.fatGrams, 0));
    const dayFiber = Math.round(scaledMeals.reduce((acc, m) => acc + m.macros.fiberGrams, 0));

    return {
      ...day,
      targetCalories: dayCalories,
      dailyMacros: {
        calories: dayCalories,
        proteinGrams: dayProtein,
        carbsGrams: dayCarbs,
        fatGrams: dayFat,
        fiberGrams: dayFiber,
      },
      meals: scaledMeals,
    };
  });

  const avgCalories = Math.round(days.reduce((acc, d) => acc + d.dailyMacros.calories, 0) / 7);
  const avgProtein = Math.round(days.reduce((acc, d) => acc + d.dailyMacros.proteinGrams, 0) / 7);
  const avgCarbs = Math.round(days.reduce((acc, d) => acc + d.dailyMacros.carbsGrams, 0) / 7);
  const avgFat = Math.round(days.reduce((acc, d) => acc + d.dailyMacros.fatGrams, 0) / 7);

  const totalMacroCalories = avgProtein * 4 + avgCarbs * 4 + avgFat * 9;
  const proteinPct = Math.round(((avgProtein * 4) / totalMacroCalories) * 100);
  const carbsPct = Math.round(((avgCarbs * 4) / totalMacroCalories) * 100);
  const fatPct = 100 - proteinPct - carbsPct;

  return {
    id: `plan-${goal}-${regionalStyle}`,
    title: 'Programme Nutritionnel Hebdomadaire AfriMacros (Pan-Algérien)',
    goal,
    regionalStyle,
    averageDailyCalories: avgCalories,
    macroRatio: {
      proteinPct,
      carbsPct,
      fatPct,
    },
    varietyMetrics: {
      uniqueDishesCount: 28, // 4 meals x 7 days = 28 distinct preparations
      plantSpeciesCount: 34, // over 34 distinct plants, seeds, spices, legumes
      regionsRepresentedCount: 5, // Algérois, Oranais, Kabyle, Constantinois, Biskri
      weeklyFiberAverageGrams: 32,
      carbCyclingDeltaKcal: 390, // Friday peak vs Wednesday recovery
    },
    days,
  };
}

